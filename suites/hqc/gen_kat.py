#!/usr/bin/env python3
"""Generate pqc_suite/kat_hqc.h from the official HQC known-answer files.

usage: gen_kat.py path/to/hqc/kats/ref > pqc_suite/kat_hqc.h

The .rsp files (https://gitlab.com/pqc-hqc/hqc, kats/ref/hqc-{1,3,5}) list,
per test, a 48-byte seed and the resulting pk, sk, ct and ss. The reference
test program seeds NIST's AES-256 CTR_DRBG with that seed and lets the KEM
draw from it: 32 bytes for the key seed, then PARAM_K bytes for the message
and 16 bytes for the salt. This script replays the DRBG, so the device only
needs the three drawn values (no AES), and stores SHA-256 fingerprints of pk
and ct plus the full shared secret. Needs the `cryptography` package.
"""
import hashlib
import sys

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

LEVELS = {1: 16, 3: 24, 5: 32}   # level -> PARAM_K
DEVICE_VECTORS = 3               # the device build keeps this many per level


class Drbg:
    def __init__(self, seed):
        self.key = bytes(32)
        self.v = bytes(16)
        self._update(seed)

    def _block(self):
        self.v = ((int.from_bytes(self.v, "big") + 1) % (1 << 128)).to_bytes(16, "big")
        enc = Cipher(algorithms.AES(self.key), modes.ECB()).encryptor()
        return enc.update(self.v) + enc.finalize()

    def _update(self, data):
        tmp = b"".join(self._block() for _ in range(3))
        if data is not None:
            tmp = bytes(a ^ b for a, b in zip(tmp, data))
        self.key, self.v = tmp[:32], tmp[32:]

    def random(self, n):
        out = b""
        while len(out) < n:
            out += self._block()
        self._update(None)
        return out[:n]


def parse(path):
    vecs, cur = [], {}
    for line in open(path):
        line = line.strip()
        if " = " in line:
            k, v = line.split(" = ", 1)
            cur[k] = v
            if k == "ss":
                vecs.append(cur)
                cur = {}
    return vecs


def carr(b):
    return "{" + ", ".join("0x%02x" % x for x in b) + "}"


def main():
    root = sys.argv[1]
    out = ["/* Known-answer test data for HQC, derived from the official files",
           " * kats/ref/hqc-{1,3,5}/PQCkemKAT_32.rsp of https://gitlab.com/pqc-hqc/hqc",
           " * (release v5.1.0). Generated by suites/hqc/gen_kat.py; see there for the",
           " * meaning of the fields. The host build checks all vectors, the device",
           " * build the first HQC_KAT_DEVICE_VECTORS of each level. */",
           "#ifndef KAT_HQC_H", "#define KAT_HQC_H", "", "#include <stdint.h>", "",
           "#define HQC_KAT_DEVICE_VECTORS %d" % DEVICE_VECTORS, "",
           "typedef struct {",
           "    uint8_t seed_kem[32];  /* DRBG output 1: key generation seed (= sk) */",
           "    uint8_t m[32];         /* DRBG output 2: message, PARAM_K bytes used */",
           "    uint8_t salt[16];      /* DRBG output 3: salt */",
           "    uint8_t pk_sha256[16]; /* first 16 bytes of SHA-256(pk) */",
           "    uint8_t ct_sha256[16]; /* first 16 bytes of SHA-256(ct) */",
           "    uint8_t ss[32];        /* shared secret */",
           "} hqc_kat_t;", ""]
    for lvl, k in LEVELS.items():
        vecs = parse("%s/hqc-%d/PQCkemKAT_32.rsp" % (root, lvl))
        assert len(vecs) == 100
        out.append("static const hqc_kat_t hqc%d_kat[] = {" % lvl)
        for i, v in enumerate(vecs):
            d = Drbg(bytes.fromhex(v["seed"]))
            seed_kem, m, salt = d.random(32), d.random(k), d.random(16)
            assert seed_kem.hex().upper() == v["sk"], "sk is the key seed"
            pk, ct, ss = bytes.fromhex(v["pk"]), bytes.fromhex(v["ct"]), bytes.fromhex(v["ss"])
            if i == DEVICE_VECTORS:
                out.append("#ifdef PQC_HOST")
            out.append("    {%s,\n     %s,\n     %s,\n     %s,\n     %s,\n     %s}," % (
                carr(seed_kem), carr(m.ljust(32, b"\0")), carr(salt),
                carr(hashlib.sha256(pk).digest()[:16]), carr(hashlib.sha256(ct).digest()[:16]),
                carr(ss)))
        out.append("#endif /* PQC_HOST */")
        out.append("};")
        out.append("")
    out.append("#endif /* KAT_HQC_H */")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
