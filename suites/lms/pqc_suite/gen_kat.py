#!/usr/bin/env python3
"""Turn the test cases of RFC 8554 (Appendix F) and RFC 9858 (Appendix A)
into lms_kat.h.

    python3 gen_kat.py rfc8554.txt rfc9858.txt > lms_kat.h

The RFC text files come from https://www.rfc-editor.org/rfc/rfcNNNN.txt.
"""
import re
import sys

HEX = re.compile(r"^[0-9a-f]+$")


def hex_of(lines):
    """Concatenate the value column: the first even-length hex token per line."""
    out = ""
    for ln in lines:
        if ln.startswith("RFC ") or "[Page" in ln:
            continue  # page header and footer
        for tok in ln.split("#")[0].split():
            if HEX.match(tok) and len(tok) % 2 == 0:
                out += tok
                break
    return bytes.fromhex(out)


def sections_8554(text):
    lines = text.splitlines()
    start = max(i for i, l in enumerate(lines) if l.startswith("Appendix F.  Test Cases"))
    end = next(i for i in range(start, len(lines)) if l_is(lines[i], "Acknowledgements"))
    heads = [(i, lines[i].strip()) for i in range(start, end) if re.match(r"^   Test Case \d ", lines[i])]
    sec = {}
    for (i, name), nxt in zip(heads, heads[1:] + [(end, "")]):
        sec[name] = lines[i + 1:nxt[0]]
    return sec


def l_is(line, word):
    return line.strip() == word


def split_private(lines):
    """Private key block: SEED and I of each tree, in order."""
    keys, cur, field = [], None, None
    for ln in lines:
        tok = ln.split()
        if not tok or ln.startswith("RFC ") or "[Page" in ln:
            continue
        if tok[0] in ("SEED", "I") and len(tok) > 1:
            field = tok[0]
            if field == "SEED":
                cur = {"SEED": "", "I": ""}
                keys.append(cur)
            cur[field] += tok[1]
        elif cur is not None and field and HEX.match(tok[0]) and len(tok[0]) % 2 == 0:
            cur[field] += tok[0]
        else:
            field = None
    return [(bytes.fromhex(k["SEED"]), bytes.fromhex(k["I"])) for k in keys]


def figures_9858(text):
    lines = text.splitlines()
    start = max(i for i, l in enumerate(lines) if l.startswith("Appendix A.  Test Cases"))
    figs, last = [], start
    for i in range(start, len(lines)):
        m = re.match(r"^\s+Figure \d+: (.*)$", lines[i])
        if m:
            figs.append((m.group(1).strip(), lines[last:i]))
            last = i + 1
    return figs


def c_array(name, data):
    body = ",".join("0x%02x" % b for b in data)
    body = "\n    ".join(re.findall(r".{1,96}(?:,|$)", body))
    return "static const uint8_t %s[%d] = {\n    %s\n};\n" % (name, len(data), body)


def main():
    t8554 = open(sys.argv[1]).read()
    t9858 = open(sys.argv[2]).read()
    cases = []

    s = sections_8554(t8554)
    cases.append(("rfc8554_tc1", [], hex_of(s["Test Case 1 Public Key"]), hex_of(s["Test Case 1 Message"]),
                  hex_of(s["Test Case 1 Signature"])))
    cases.append(("rfc8554_tc2", split_private(s["Test Case 2 Private Key"]),
                  hex_of(s["Test Case 2 Public Key"]), hex_of(s["Test Case 2 Message"]),
                  hex_of(s["Test Case 2 Signature"])))

    figs = figures_9858(t9858)
    for n in range(len(figs) // 4):
        priv, pub, msg, sig = figs[4 * n:4 * n + 4]
        assert priv[0].startswith("Private Key") and pub[0].startswith("Public Key"), (priv[0], pub[0])
        assert msg[0].startswith("Message") and sig[0].startswith("Signature"), (msg[0], sig[0])
        cases.append(("rfc9858_tc%d" % (n + 1), split_private(priv[1]), hex_of(pub[1]), hex_of(msg[1]),
                      hex_of(sig[1])))

    print("/* Test cases of RFC 8554 Appendix F and RFC 9858 Appendix A.")
    print(" * Generated by gen_kat.py from the RFC text; do not edit. */")
    print("#ifndef LMS_KAT_H\n#define LMS_KAT_H\n\n#include <stddef.h>\n#include <stdint.h>\n")
    for name, priv, pub, msg, sig in cases:
        for i, (seed, ident) in enumerate(priv):
            print(c_array("%s_seed%d" % (name, i), seed))
            print(c_array("%s_i%d" % (name, i), ident))
        print(c_array(name + "_pk", pub))
        print(c_array(name + "_msg", msg))
        print(c_array(name + "_sig", sig))
    print("typedef struct {\n    const char *name;\n    const uint8_t *seed[2], *ident[2];\n"
          "    const uint8_t *pk, *msg, *sig;\n    size_t pklen, msglen, siglen;\n} lms_kat_t;\n")
    print("static const lms_kat_t lms_kats[] = {")
    for name, priv, pub, msg, sig in cases:
        seeds = ["%s_seed%d" % (name, i) for i in range(len(priv))] + ["NULL"] * (2 - len(priv))
        ids = ["%s_i%d" % (name, i) for i in range(len(priv))] + ["NULL"] * (2 - len(priv))
        print("    {\"%s\", {%s}, {%s}, %s_pk, %s_msg, %s_sig, %d, %d, %d}," %
              (name, ", ".join(seeds), ", ".join(ids), name, name, name, len(pub), len(msg), len(sig)))
    print("};\n\n#endif /* LMS_KAT_H */")
    for name, priv, pub, msg, sig in cases:
        sys.stderr.write("%s: %d private trees, pk %d, msg %d, sig %d bytes\n" %
                         (name, len(priv), len(pub), len(msg), len(sig)))


if __name__ == "__main__":
    main()
