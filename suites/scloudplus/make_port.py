#!/usr/bin/env python3
"""Prepare the fetched SCloud+ sources for this project.

SCloud+ is fetched into downloads/scloudplus and never committed, so nothing
is edited in place. This script writes two derived files next to it:

  downloads/scloudplus_port/hash_aes_shake.c   Keccak-f[1600] through pqc_prims.h
  downloads/scloudplus_port/sm3_reference.c    SM3 compression through pqc_prims.h

and the known-answer header of the suite, built from the submitters' own
test vectors (seed and SHA-256 of the expected outputs of the first vector):

  suites/scloudplus/pqc_suite/kat_expected.h
"""
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "downloads", "scloudplus")
CORE = os.path.join(SRC, "Implementations", "_shared", "scloudplus_core")
PORT = os.path.join(ROOT, "downloads", "scloudplus_port")
SUITE = os.path.join(ROOT, "suites", "scloudplus", "pqc_suite")


def patch(path, old, new):
    s = open(path).read()
    if s.count(old) != 1:
        sys.exit("unexpected upstream source, cannot port " + path)
    return s.replace(old, new)


def port_sources():
    os.makedirs(PORT, exist_ok=True)
    s = patch(os.path.join(CORE, "common", "hash_aes_shake.c"),
              "static void KeccakF1600_StatePermute(uint64_t state[25])\n{\n",
              "#ifdef PQC_PRIMS_KECCAK\n#include \"pqc_prims.h\"\n#endif\n"
              "static void KeccakF1600_StatePermute(uint64_t state[25])\n{\n"
              "#ifdef PQC_PRIMS_KECCAK\n\tpqc_keccakf1600(state);\n\treturn;\n#endif\n")
    open(os.path.join(PORT, "hash_aes_shake.c"), "w").write(s)
    s = patch(os.path.join(CORE, "ref", "sm3_reference.c"),
              "static void sm3_bit_compress(unsigned int dgst[8], const unsigned char *msg, "
              "unsigned long long blocks)\n{\n",
              "#ifdef PQC_PRIMS_SM3\n#include \"pqc_prims.h\"\n#endif\n"
              "static void sm3_bit_compress(unsigned int dgst[8], const unsigned char *msg, "
              "unsigned long long blocks)\n{\n"
              "#ifdef PQC_PRIMS_SM3\n\tpqc_sm3_compress((uint32_t *)dgst, msg, (size_t)blocks);\n"
              "\treturn;\n#endif\n")
    open(os.path.join(PORT, "sm3_reference.c"), "w").write(s)


def first_vector(path):
    fields = {}
    for line in open(path):
        m = re.match(r"(\w+) = ([0-9A-Fa-f]*)\s*$", line)
        if m and m.group(1) in ("Seed", "PK", "SK", "CT", "SS") and m.group(1) not in fields:
            fields[m.group(1)] = bytes.fromhex(m.group(2))
        if line.startswith("Count = 1"):
            break
    return fields


def c_bytes(b):
    return ", ".join("0x%02x" % x for x in b)


def kat_header():
    out = ["/* Generated by suites/scloudplus/make_port.py from the SCloud+ submission's",
           " * Test_Vectors (first vector of each file): the DRNG seed, and the SHA-256",
           " * of the public key, secret key, ciphertext and shared secret it must give. */",
           "#ifndef SCLOUDPLUS_KAT_EXPECTED_H", "#define SCLOUDPLUS_KAT_EXPECTED_H", "",
           "typedef struct {", "    unsigned char seed[64];",
           "    unsigned char pk[32], sk[32], ct[32], ss[32];", "} scloudplus_kat;", ""]
    for level in (128, 192, 256, 384, 512):
        for fam in ("SM3", "SHAKE", "AES"):
            f = first_vector(os.path.join(SRC, "Test_Vectors",
                                          "KAT_KEM_Scloudplus-%d-%s-packed10.txt" % (level, fam)))
            out.append("static const scloudplus_kat scloudplus_kat_%d_%s = {" % (level, fam.lower()))
            out.append("    {%s}," % c_bytes(f["Seed"]))
            for k in ("PK", "SK", "CT", "SS"):
                out.append("    {%s}," % c_bytes(hashlib.sha256(f[k]).digest()))
            out.append("};")
            out.append("")
    out.append("#endif")
    open(os.path.join(SUITE, "kat_expected.h"), "w").write("\n".join(out) + "\n")


if __name__ == "__main__":
    port_sources()
    kat_header()
    print("SCloud+ port files written to", os.path.relpath(PORT, ROOT))
