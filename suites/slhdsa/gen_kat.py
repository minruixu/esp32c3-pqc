#!/usr/bin/env python3
"""Generate pqc_suite/kat_vectors.h from the NIST ACVP sample vectors.

Usage: python3 suites/slhdsa/gen_kat.py   (from the repository root)

The JSON files come from https://github.com/usnistgov/ACVP-Server (tag
v1.1.0.40, gen-val/json-files/SLH-DSA-*-FIPS205/internalProjection.json) and
are cached under downloads/acvp/. For each of the 12 parameter sets the
header holds:

  - one key-generation vector (seeds in, public and private key out);
  - one deterministic signature vector for the external, pure interface
    (the one with the shortest message and context): the expected signature
    is stored as its SHA-256, because the signatures are 8 to 50 KB each;
  - for the "f" sets, one hedged signature vector for the internal interface
    (with additional randomness), also as SHA-256.

It also holds two verification vectors in full (8 KB each, which is what the
image has room for): a valid signature for SLH-DSA-SHA2-128s, and for
SLH-DSA-SHAKE-128s one whose hypertree part was modified and must be
rejected.
"""
import hashlib
import json
import os
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
CACHE = os.path.join(ROOT, "downloads", "acvp")
TAG = "v1.1.0.40"
BASE = "https://raw.githubusercontent.com/usnistgov/ACVP-Server/%s/gen-val/json-files/" % TAG
SETS = ["SHA2-128s", "SHA2-128f", "SHA2-192s", "SHA2-192f", "SHA2-256s", "SHA2-256f",
        "SHAKE-128s", "SHAKE-128f", "SHAKE-192s", "SHAKE-192f", "SHAKE-256s", "SHAKE-256f"]


def load(name):
    path = os.path.join(CACHE, name, "internalProjection.json")
    if not os.path.exists(path):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        print("downloading", name, file=sys.stderr)
        urllib.request.urlretrieve(BASE + name + "/internalProjection.json", path)
    return json.load(open(path))


def carr(name, hexstr):
    b = bytes.fromhex(hexstr)
    if not b:
        return "static const uint8_t %s[1] = {0};\n" % name
    rows = []
    for i in range(0, len(b), 16):
        rows.append("    " + ", ".join("0x%02x" % x for x in b[i:i + 16]))
    return "static const uint8_t %s[%d] = {\n%s};\n" % (name, len(b), ",\n".join(rows))


def ident(s):
    return s.lower().replace("-", "_")


def main():
    kg = load("SLH-DSA-keyGen-FIPS205")
    sg = load("SLH-DSA-sigGen-FIPS205")
    sv = load("SLH-DSA-sigVer-FIPS205")
    out = ["/* Generated by suites/slhdsa/gen_kat.py from the NIST ACVP sample vectors\n"
           " * (usnistgov/ACVP-Server %s, SLH-DSA-{keyGen,sigGen,sigVer}-FIPS205).\n"
           " * Do not edit. */\n#ifndef SLH_KAT_VECTORS_H\n#define SLH_KAT_VECTORS_H\n\n"
           "#include <stddef.h>\n#include <stdint.h>\n\n" % TAG]
    table = []
    vtable = []
    for s in SETS:
        full = "SLH-DSA-" + s
        k = ident(s)
        # key generation: first test of the group
        t = next(g for g in kg["testGroups"] if g["parameterSet"] == full)["tests"][0]
        out.append("/* %s: keyGen tcId %d */\n" % (full, t["tcId"]))
        out.append(carr("kg_%s_skseed" % k, t["skSeed"]))
        out.append(carr("kg_%s_skprf" % k, t["skPrf"]))
        out.append(carr("kg_%s_pkseed" % k, t["pkSeed"]))
        out.append(carr("kg_%s_sk" % k, t["sk"]))
        out.append(carr("kg_%s_pk" % k, t["pk"]))
        kg_tc = t["tcId"]

        # deterministic, external interface, pure
        g = next(g for g in sg["testGroups"] if g["parameterSet"] == full and g["deterministic"]
                 and g["signatureInterface"] == "external" and g["preHash"] == "pure")
        t = min(g["tests"], key=lambda t: len(t["message"]) + len(t["context"]))
        out.append("/* %s: sigGen tcId %d (deterministic, external, pure) */\n" % (full, t["tcId"]))
        out.append(carr("sg_%s_sk" % k, t["sk"]))
        out.append(carr("sg_%s_msg" % k, t["message"]))
        out.append(carr("sg_%s_ctx" % k, t["context"]))
        out.append(carr("sg_%s_sighash" % k, hashlib.sha256(bytes.fromhex(t["signature"])).hexdigest()))
        sg_tc, mlen, clen, siglen = t["tcId"], len(t["message"]) // 2, len(t["context"]) // 2, len(t["signature"]) // 2

        # hedged, internal interface (only used for the fast sets)
        hg = "NULL, NULL, NULL, 0, NULL, 0"
        if s.endswith("f"):
            g = next(g for g in sg["testGroups"] if g["parameterSet"] == full and not g["deterministic"]
                     and g["signatureInterface"] == "internal")
            t = min(g["tests"], key=lambda t: len(t["message"]))
            out.append("/* %s: sigGen tcId %d (hedged, internal) */\n" % (full, t["tcId"]))
            out.append(carr("hg_%s_sk" % k, t["sk"]))
            out.append(carr("hg_%s_rnd" % k, t["additionalRandomness"]))
            out.append(carr("hg_%s_msg" % k, t["message"]))
            out.append(carr("hg_%s_sighash" % k, hashlib.sha256(bytes.fromhex(t["signature"])).hexdigest()))
            hg = "hg_%s_sk, hg_%s_rnd, hg_%s_msg, %d, hg_%s_sighash, %d" % (k, k, k, len(t["message"]) // 2, k, t["tcId"])
        table.append('    {"%s", kg_%s_skseed, kg_%s_skprf, kg_%s_pkseed, kg_%s_sk, kg_%s_pk, %d,\n'
                     '     sg_%s_sk, sg_%s_msg, %d, sg_%s_ctx, %d, sg_%s_sighash, %d, %d,\n     %s},\n'
                     % (full, k, k, k, k, k, kg_tc, k, k, mlen, k, clen, k, siglen, sg_tc, hg))

        # verification vectors in full, for the two small sets
        if s.endswith("128s"):
            ext = next(g for g in sv["testGroups"] if g["parameterSet"] == full
                       and g["signatureInterface"] == "external" and g["preHash"] == "pure")
            good = min((t for t in ext["tests"] if t["testPassed"]),
                       key=lambda t: len(t["message"]) + len(t["context"]))
            itn = next(g for g in sv["testGroups"] if g["parameterSet"] == full
                       and g["signatureInterface"] == "internal")
            bad = min((t for t in itn["tests"] if not t["testPassed"] and "SIGHT" in t["reason"]),
                      key=lambda t: len(t["message"]))
            keep = (("good", good, 0),) if s.startswith("SHA2") else (("bad", bad, 1),)
            for tag, t, internal in keep:
                out.append("/* %s: sigVer tcId %d (%s) */\n" % (full, t["tcId"], t["reason"]))
                out.append(carr("sv_%s_%s_pk" % (k, tag), t["pk"]))
                out.append(carr("sv_%s_%s_msg" % (k, tag), t["message"]))
                out.append(carr("sv_%s_%s_ctx" % (k, tag), t.get("context", "")))
                out.append(carr("sv_%s_%s_sig" % (k, tag), t["signature"]))
                vtable.append('    {"%s", %d, %d, sv_%s_%s_pk, sv_%s_%s_msg, %d, sv_%s_%s_ctx, %d, sv_%s_%s_sig, %d, %d},\n'
                              % (full, t["tcId"], internal, k, tag, k, tag, len(t["message"]) // 2, k, tag,
                                 len(t.get("context", "")) // 2, k, tag, len(t["signature"]) // 2,
                                 1 if t["testPassed"] else 0))

    out.append("""
typedef struct {
    const char *alg;
    const uint8_t *kg_skseed, *kg_skprf, *kg_pkseed, *kg_sk, *kg_pk;
    int kg_tcid;
    const uint8_t *sg_sk, *sg_msg;
    size_t sg_msg_len;
    const uint8_t *sg_ctx;
    size_t sg_ctx_len;
    const uint8_t *sg_sighash; /* SHA-256 of the expected signature */
    size_t sig_len;
    int sg_tcid;
    const uint8_t *hg_sk, *hg_rnd, *hg_msg; /* hedged vector, NULL if none */
    size_t hg_msg_len;
    const uint8_t *hg_sighash;
    int hg_tcid;
} slh_kat_t;

static const slh_kat_t slh_kats[] = {
""")
    out.extend(table)
    out.append("""};

typedef struct {
    const char *alg;
    int tcid;
    int internal; /* 1: internal interface (no context), 0: external, pure */
    const uint8_t *pk, *msg;
    size_t msg_len;
    const uint8_t *ctx;
    size_t ctx_len;
    const uint8_t *sig;
    size_t sig_len;
    int expect; /* 1: must verify, 0: must be rejected */
} slh_ver_kat_t;

static const slh_ver_kat_t slh_ver_kats[] = {
""")
    out.extend(vtable)
    out.append("};\n\n#endif /* SLH_KAT_VECTORS_H */\n")
    path = os.path.join(ROOT, "suites", "slhdsa", "pqc_suite", "kat_vectors.h")
    open(path, "w").write("".join(out))
    print("wrote %s (%d bytes)" % (os.path.relpath(path, ROOT), os.path.getsize(path)))


if __name__ == "__main__":
    main()
