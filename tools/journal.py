#!/usr/bin/env python3
"""Render the optimization journal.

    python3 tools/journal.py

Writes two files on the `optimization-journal` branch:

- journal/EXPERIMENTS.md, from journal/experiments/*.jsonl: every optimization
  attempt with its before/after numbers and verdict.
- journal/PROGRESS.md, from the history of results/*.json in git: how the time
  of each job moved from commit to commit.
"""
import glob
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JOURNAL = os.path.join(ROOT, "journal")


def num(v):
    if v is None:
        return "n/a"
    if isinstance(v, float) and not v.is_integer():
        return "%g" % v
    return "{:,}".format(int(v))


def gain(b, a):
    if b is None or a is None or not a or not b:
        return ""
    r = float(b) / float(a)
    return "%.2f×" % r if r < 10 else "%.0f×" % r


def experiments():
    out = ["# Experiments", "",
           "Every optimization attempt, kept or not. Generated by `tools/journal.py` from",
           "`journal/experiments/*.jsonl`; the method is in `METHOD.md`.", ""]
    total = {}
    bad = []
    for path in sorted(glob.glob(os.path.join(JOURNAL, "experiments", "*.jsonl"))):
        rows = []
        for i, line in enumerate(open(path), 1):
            line = line.strip()
            if not line:
                continue
            try:
                rows.append(json.loads(line))
            except ValueError as e:
                bad.append("%s:%d %s" % (os.path.basename(path), i, e))
        if not rows:
            continue
        name = os.path.basename(path)[:-6]
        out += ["## %s" % name, "",
                "| Id | Target | Metric | Before | After | Gain | Verdict |",
                "|---|---|---|---:|---:|---:|---|"]
        for r in rows:
            v = r.get("verdict", "?")
            total[v] = total.get(v, 0) + 1
            out.append("| %s | %s | %s | %s | %s | %s | %s |" % (
                r.get("id", ""), r.get("target", ""), r.get("metric", ""), num(r.get("before")),
                num(r.get("after")), gain(r.get("before"), r.get("after")), v))
        out.append("")
        for r in rows:
            out.append("**%s** (%s, %s). %s" % (r.get("id", ""), r.get("verdict", "?"), r.get("date", ""),
                                                r.get("idea", "")))
            out.append("")
            if r.get("change"):
                out.append("- Change: %s" % r["change"])
            if r.get("checked"):
                out.append("- Checked by: %s" % r["checked"])
            if r.get("note"):
                out.append("- Note: %s" % r["note"])
            out.append("")
    summary = ", ".join("%d %s" % (n, v) for v, n in sorted(total.items()))
    out.insert(4, "Total: %s." % summary if summary else "No experiments recorded yet.")
    out.insert(5, "")
    with open(os.path.join(JOURNAL, "EXPERIMENTS.md"), "w") as f:
        f.write("\n".join(out).rstrip("\n") + "\n")
    for b in bad:
        print("unreadable line:", b, file=sys.stderr)
    return sum(total.values())


def git(*args):
    return subprocess.run(["git"] + list(args), cwd=ROOT, capture_output=True, text=True).stdout


def progress():
    commits = [l.split("|", 2) for l in
               git("log", "--first-parent", "--reverse", "--format=%h|%ad|%s", "--date=short", "--", "results").splitlines()]
    series = {}   # (suite, job) -> list of (commit, date, avg_us)
    for h, date, _subject in commits:
        files = git("ls-tree", "-r", "--name-only", h, "results").splitlines()
        for path in files:
            if not path.endswith(".json") or path.endswith(".host.json") or path.count("/") != 1:
                continue
            try:
                data = json.loads(git("show", "%s:%s" % (h, path)))
            except ValueError:
                continue
            suite = os.path.basename(path)[:-5]
            for job, r in data.get("results", {}).items():
                if r.get("rc") != 0 or not r.get("avg_us"):
                    continue
                pts = series.setdefault((suite, job), [])
                if not pts or abs(r["avg_us"] - pts[-1][2]) > 0.01 * pts[-1][2]:
                    pts.append((h, date, r["avg_us"]))
    out = ["# Progress", "",
           "How the average time of each job moved as the work went on, read from the history of",
           "`results/*.json` on this branch. A job is listed once its time changed by more than 1%",
           "between two commits. Times in microseconds. Generated by `tools/journal.py`.", ""]
    suites = sorted({s for s, _ in series})
    listed = 0
    for s in suites:
        rows = [(job, pts) for (su, job), pts in sorted(series.items()) if su == s and len(pts) > 1]
        if not rows:
            continue
        out += ["## %s" % s, "", "| Job | First | Last | Change | Steps (commit: time) |", "|---|---:|---:|---:|---|"]
        for job, pts in rows:
            steps = " → ".join("`%s`: %s" % (h, num(v)) for h, _d, v in pts)
            out.append("| %s | %s | %s | %s | %s |" % (job, num(pts[0][2]), num(pts[-1][2]),
                                                      gain(pts[0][2], pts[-1][2]), steps))
            listed += 1
        out.append("")
    if not listed:
        out.append("No job has changed between commits yet.")
    with open(os.path.join(JOURNAL, "PROGRESS.md"), "w") as f:
        f.write("\n".join(out).rstrip("\n") + "\n")
    return listed, len(commits)


def main():
    n = experiments()
    jobs, commits = progress()
    print("journal: %d experiments; progress of %d jobs over %d commits" % (n, jobs, commits))


if __name__ == "__main__":
    main()
